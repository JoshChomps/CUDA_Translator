"""AMD ROCm / HIP C++ Kernel Code Generator."""

from __future__ import annotations
from typing import List, Any
from cuda_translator.ir.module import Module, Kernel
from cuda_translator.ir.instructions import (
    Instruction, AllocaInst, LoadInst, StoreInst, BinaryOpInst, UnaryOpInst,
    FusedMultiplyAddInst, CompareInst, ConvertInst, BranchInst, BarrierInst,
    SubgroupShuffleInst, SubgroupBallotInst, CooperativeMatrixLoadInst,
    CooperativeMatrixStoreInst, CooperativeMatrixMulAddInst, ReturnInst
)
from cuda_translator.ir.types import AddressSpace


class HIPBackend:
    """Emits native AMD ROCm / HIP C++ kernels from Neutral IR."""

    def __init__(self, target_wavefront_size: int = 64) -> None:
        self.target_wavefront_size = target_wavefront_size

    def generate(self, module: Module) -> str:
        """Generate full HIP C++ compilation unit."""
        lines: List[str] = [
            "// Auto-generated by CUDA_Translator - AMD ROCm / HIP Backend",
            "#include <hip/hip_runtime.h>",
            "#include <rocwmma/rocwmma.hpp>",
            "",
            "using namespace rocwmma;",
            ""
        ]

        for kernel in module.kernels:
            lines.extend(self._emit_kernel(kernel))

        return "\n".join(lines)

    def _emit_kernel(self, kernel: Kernel) -> List[str]:
        lines: List[str] = []

        # Build parameter list
        param_strs = []
        for param in kernel.params:
            hip_type = self._map_type(param.data_type)
            if param.is_pointer:
                param_strs.append(f"{hip_type}* __restrict__ {param.name}")
            else:
                param_strs.append(f"{hip_type} {param.name}")

        params_joined = ", ".join(param_strs)
        lines.append(f"__global__ void {kernel.name}({params_joined}) {{")
        lines.append("    // Thread and block indexing")
        lines.append("    unsigned int tid_x = threadIdx.x;")
        lines.append("    unsigned int ctaid_x = blockIdx.x;")
        lines.append("    unsigned int ntid_x = blockDim.x;")
        lines.append("    unsigned int global_idx = ctaid_x * ntid_x + tid_x;")
        lines.append("")

        # Emit shared memory allocations (__shared__)
        for alloc in kernel.shared_allocs:
            elem_type = self._map_type(alloc.element_type)
            lines.append(f"    __shared__ {elem_type} {alloc.name}[{alloc.count}];")

        # Declare registers
        for reg_name, reg_type in kernel.registers.items():
            clean_reg = self._clean_reg_name(reg_name)
            hip_type = self._map_type(reg_type)
            lines.append(f"    {hip_type} {clean_reg};")

        lines.append("")

        # Emit instructions
        for block in kernel.blocks:
            lines.append(f"    // Block: {block.label}")
            for inst in block.instructions:
                code = self._emit_instruction(inst, kernel)
                if code:
                    lines.append(f"    {code}")

        lines.append("}")
        lines.append("")
        return lines

    def _emit_instruction(self, inst: Instruction, kernel: Kernel) -> str:
        guard = ""
        if inst.predicate:
            p_name = self._clean_reg_name(inst.predicate)
            guard = f"if (!{p_name}) " if inst.pred_negated else f"if ({p_name}) "

        if isinstance(inst, LoadInst):
            dest = self._clean_reg_name(inst.dest)
            if inst.space == AddressSpace.PARAM:
                return f"{guard}{dest} = {self._clean_reg_name(inst.ptr)};"
            elif inst.space == AddressSpace.SHARED:
                return f"{guard}{dest} = {self._clean_reg_name(inst.ptr)}[tid_x];"
            else:
                return f"{guard}{dest} = {self._clean_reg_name(inst.ptr)}[global_idx];"

        elif isinstance(inst, StoreInst):
            src = self._clean_reg_name(inst.src)
            if inst.space == AddressSpace.SHARED:
                return f"{guard}{self._clean_reg_name(inst.ptr)}[tid_x] = {src};"
            else:
                return f"{guard}{self._clean_reg_name(inst.ptr)}[global_idx] = {src};"

        elif isinstance(inst, BinaryOpInst):
            dest = self._clean_reg_name(inst.dest)
            s1 = self._clean_reg_name(inst.src1)
            s2 = self._clean_reg_name(inst.src2)
            op_map = {
                "add": "+", "sub": "-", "mul": "*", "div": "/", "rem": "%",
                "and": "&", "or": "|", "xor": "^", "shl": "<<", "shr": ">>"
            }
            sym = op_map.get(inst.op, "+")
            return f"{guard}{dest} = {s1} {sym} {s2};"

        elif isinstance(inst, UnaryOpInst):
            dest = self._clean_reg_name(inst.dest)
            s = self._clean_reg_name(inst.src)
            if inst.op == "neg":
                return f"{guard}{dest} = -{s};"
            elif inst.op == "not":
                return f"{guard}{dest} = ~{s};"
            elif inst.op == "sqrt":
                return f"{guard}{dest} = sqrtf({s});"
            elif inst.op == "rsqrt":
                return f"{guard}{dest} = rsqrtf({s});"
            return f"{guard}{dest} = {s};"

        elif isinstance(inst, FusedMultiplyAddInst):
            dest = self._clean_reg_name(inst.dest)
            sa = self._clean_reg_name(inst.src_a)
            sb = self._clean_reg_name(inst.src_b)
            sc = self._clean_reg_name(inst.src_c)
            return f"{guard}{dest} = fmaf({sa}, {sb}, {sc});"

        elif isinstance(inst, CompareInst):
            dest = self._clean_reg_name(inst.dest)
            s1 = self._clean_reg_name(inst.src1)
            s2 = self._clean_reg_name(inst.src2)
            cond_map = {
                "eq": "==", "ne": "!=", "lt": "<", "le": "<=", "gt": ">", "ge": ">="
            }
            sym = cond_map.get(inst.cond, "==")
            return f"{guard}{dest} = ({s1} {sym} {s2});"

        elif isinstance(inst, ConvertInst):
            dest = self._clean_reg_name(inst.dest)
            src = self._clean_reg_name(inst.src)
            if "%tid.x" in src:
                src = "tid_x"
            elif "%ctaid.x" in src:
                src = "ctaid_x"
            elif "%ntid.x" in src:
                src = "ntid_x"
            return f"{guard}{dest} = {src};"

        elif isinstance(inst, BarrierInst):
            return f"{guard}__syncthreads();"

        elif isinstance(inst, SubgroupShuffleInst):
            dest = self._clean_reg_name(inst.dest)
            src = self._clean_reg_name(inst.src)
            delta = inst.delta_or_lane
            width = inst.width
            if inst.mode == "bfly":
                return f"{guard}{dest} = __shfl_xor({src}, {delta}, {width});"
            elif inst.mode == "down":
                return f"{guard}{dest} = __shfl_down({src}, {delta}, {width});"
            elif inst.mode == "up":
                return f"{guard}{dest} = __shfl_up({src}, {delta}, {width});"
            return f"{guard}{dest} = __shfl({src}, {delta}, {width});"

        elif isinstance(inst, SubgroupBallotInst):
            dest = self._clean_reg_name(inst.dest)
            p = self._clean_reg_name(inst.pred)
            return f"{guard}{dest} = __ballot({p});"

        elif isinstance(inst, CooperativeMatrixLoadInst):
            dest = self._clean_reg_name(inst.dest_frag)
            ptr = self._clean_reg_name(inst.ptr)
            return f"{guard}rocwmma::load_matrix_sync({dest}, {ptr}, {inst.stride});"

        elif isinstance(inst, CooperativeMatrixMulAddInst):
            dest = self._clean_reg_name(inst.dest_frag)
            fa = self._clean_reg_name(inst.frag_a)
            fb = self._clean_reg_name(inst.frag_b)
            fc = self._clean_reg_name(inst.frag_c)
            return f"{guard}rocwmma::mma_sync({dest}, {fa}, {fb}, {fc});"

        elif isinstance(inst, CooperativeMatrixStoreInst):
            src = self._clean_reg_name(inst.src_frag)
            ptr = self._clean_reg_name(inst.ptr)
            return f"{guard}rocwmma::store_matrix_sync({ptr}, {src}, {inst.stride}, rocwmma::mem_row_major);"

        elif isinstance(inst, ReturnInst):
            return f"{guard}return;"

        return ""

    def _clean_reg_name(self, name: str) -> str:
        """Strip %, brackets, and special symbols to make valid C++ identifier."""
        return name.replace("%", "r_").replace(".", "_").replace("$", "_").replace("[", "").replace("]", "").strip()

    def _map_type(self, t: Any) -> str:
        name = str(t).lower()
        mapping = {
            "f16": "__half", "f32": "float", "f64": "double",
            "s8": "int8_t", "s16": "int16_t", "s32": "int", "s64": "int64_t",
            "u8": "uint8_t", "u16": "uint16_t", "u32": "unsigned int", "u64": "uint64_t",
            "b8": "uint8_t", "b16": "uint16_t", "b32": "unsigned int", "b64": "uint64_t",
            "pred": "bool"
        }
        return mapping.get(name, "unsigned int")
