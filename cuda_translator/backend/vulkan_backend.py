"""Universal Vulkan Compute Shader (GLSL/SPIR-V) Code Generator."""

from __future__ import annotations
from typing import List
from cuda_translator.ir.module import Module, Kernel
from cuda_translator.ir.instructions import (
    Instruction, AllocaInst, LoadInst, StoreInst, BinaryOpInst, UnaryOpInst,
    FusedMultiplyAddInst, CompareInst, ConvertInst, BranchInst, BarrierInst,
    SubgroupShuffleInst, SubgroupBallotInst, CooperativeMatrixLoadInst,
    CooperativeMatrixStoreInst, CooperativeMatrixMulAddInst, ReturnInst
)
from cuda_translator.ir.types import AddressSpace, F16, F32, F64, S32, U32, U64, B32, PRED


class VulkanBackend:
    """Emits universal Vulkan Compute Shaders (GLSL/SPIR-V compatible) from Neutral IR."""

    def __init__(self, local_size_x: int = 32, local_size_y: int = 1, local_size_z: int = 1) -> None:
        self.local_size_x = local_size_x
        self.local_size_y = local_size_y
        self.local_size_z = local_size_z

    def generate(self, module: Module) -> str:
        """Generate Vulkan compute shader source code for all kernels in module."""
        lines: List[str] = [
            "// Auto-generated by CUDA_Translator - Universal Vulkan Compute Backend",
            "#version 450",
            "#extension GL_KHR_shader_subgroup_basic : enable",
            "#extension GL_KHR_shader_subgroup_shuffle : enable",
            "#extension GL_KHR_shader_subgroup_ballot : enable",
            "#extension GL_KHR_cooperative_matrix : enable",
            "#extension GL_EXT_shader_explicit_arithmetic_types_float16 : enable",
            "",
            f"layout(local_size_x = {self.local_size_x}, local_size_y = {self.local_size_y}, local_size_z = {self.local_size_z}) in;",
            ""
        ]

        for kernel in module.kernels:
            lines.extend(self._emit_kernel(kernel))

        return "\n".join(lines)

    def _emit_kernel(self, kernel: Kernel) -> List[str]:
        lines: List[str] = []

        # Emit storage buffer bindings for pointer parameters
        binding = 0
        for param in kernel.params:
            if param.is_pointer:
                glsl_type = self._map_type(param.data_type)
                lines.append(f"layout(std430, set = 0, binding = {binding}) buffer Buffer_{param.name} {{")
                lines.append(f"    {glsl_type} data_{param.name}[];")
                lines.append("};")
                binding += 1

        # Emit uniform parameters block if scalar arguments exist
        scalar_params = [p for p in kernel.params if not p.is_pointer]
        if scalar_params:
            lines.append(f"layout(std140, set = 0, binding = {binding}) uniform PushConstants {{")
            for p in scalar_params:
                lines.append(f"    {self._map_type(p.data_type)} {p.name};")
            lines.append("};")
            binding += 1

        # Emit shared memory allocations (workgroup storage)
        for alloc in kernel.shared_allocs:
            elem_type = self._map_type(alloc.element_type)
            lines.append(f"shared {elem_type} {alloc.name}[{alloc.count}];")

        lines.append("")
        lines.append(f"void main() {{")
        lines.append("    // Hardware thread indexing mapping")
        lines.append("    uint tid_x = gl_LocalInvocationID.x;")
        lines.append("    uint ctaid_x = gl_WorkGroupID.x;")
        lines.append("    uint ntid_x = gl_WorkGroupSize.x;")
        lines.append("    uint global_idx = ctaid_x * ntid_x + tid_x;")
        lines.append("")

        # Declare registers
        for reg_name, reg_type in kernel.registers.items():
            clean_reg = self._clean_reg_name(reg_name)
            glsl_type = self._map_type(reg_type)
            lines.append(f"    {glsl_type} {clean_reg};")

        lines.append("")

        # Emit blocks
        for block in kernel.blocks:
            lines.append(f"    // BasicBlock: {block.label}")
            for inst in block.instructions:
                code = self._emit_instruction(inst, kernel)
                if code:
                    lines.append(f"    {code}")

        lines.append("}")
        return lines

    def _emit_instruction(self, inst: Instruction, kernel: Kernel) -> str:
        guard = ""
        if inst.predicate:
            p_name = self._clean_reg_name(inst.predicate)
            guard = f"if (!{p_name}) " if inst.pred_negated else f"if ({p_name}) "

        if isinstance(inst, LoadInst):
            dest = self._clean_reg_name(inst.dest)
            if inst.space == AddressSpace.PARAM:
                return f"{guard}{dest} = {self._clean_reg_name(inst.ptr)};"
            elif inst.space == AddressSpace.SHARED:
                return f"{guard}{dest} = {self._clean_reg_name(inst.ptr)}[tid_x];"
            else:
                return f"{guard}{dest} = data_{self._clean_reg_name(inst.ptr)}[global_idx];"

        elif isinstance(inst, StoreInst):
            src = self._clean_reg_name(inst.src)
            if inst.space == AddressSpace.SHARED:
                return f"{guard}{self._clean_reg_name(inst.ptr)}[tid_x] = {src};"
            else:
                return f"{guard}data_{self._clean_reg_name(inst.ptr)}[global_idx] = {src};"

        elif isinstance(inst, BinaryOpInst):
            dest = self._clean_reg_name(inst.dest)
            s1 = self._clean_reg_name(inst.src1)
            s2 = self._clean_reg_name(inst.src2)
            op_map = {
                "add": "+", "sub": "-", "mul": "*", "div": "/", "rem": "%",
                "and": "&", "or": "|", "xor": "^", "shl": "<<", "shr": ">>"
            }
            sym = op_map.get(inst.op, "+")
            return f"{guard}{dest} = {s1} {sym} {s2};"

        elif isinstance(inst, UnaryOpInst):
            dest = self._clean_reg_name(inst.dest)
            s = self._clean_reg_name(inst.src)
            if inst.op == "neg":
                return f"{guard}{dest} = -{s};"
            elif inst.op == "not":
                return f"{guard}{dest} = ~{s};"
            elif inst.op == "sqrt":
                return f"{guard}{dest} = sqrt({s});"
            elif inst.op == "rsqrt":
                return f"{guard}{dest} = inversesqrt({s});"
            return f"{guard}{dest} = {s};"

        elif isinstance(inst, FusedMultiplyAddInst):
            dest = self._clean_reg_name(inst.dest)
            sa = self._clean_reg_name(inst.src_a)
            sb = self._clean_reg_name(inst.src_b)
            sc = self._clean_reg_name(inst.src_c)
            return f"{guard}{dest} = fma({sa}, {sb}, {sc});"

        elif isinstance(inst, CompareInst):
            dest = self._clean_reg_name(inst.dest)
            s1 = self._clean_reg_name(inst.src1)
            s2 = self._clean_reg_name(inst.src2)
            cond_map = {
                "eq": "==", "ne": "!=", "lt": "<", "le": "<=", "gt": ">", "ge": ">="
            }
            sym = cond_map.get(inst.cond, "==")
            return f"{guard}{dest} = ({s1} {sym} {s2});"

        elif isinstance(inst, ConvertInst):
            dest = self._clean_reg_name(inst.dest)
            src = self._clean_reg_name(inst.src)
            # Handle special registers
            if "%tid.x" in src:
                src = "tid_x"
            elif "%ctaid.x" in src:
                src = "ctaid_x"
            elif "%ntid.x" in src:
                src = "ntid_x"
            return f"{guard}{dest} = {src};"

        elif isinstance(inst, BarrierInst):
            return f"{guard}barrier(); memoryBarrierShared();"

        elif isinstance(inst, SubgroupShuffleInst):
            dest = self._clean_reg_name(inst.dest)
            src = self._clean_reg_name(inst.src)
            delta = inst.delta_or_lane
            if inst.mode == "bfly":
                return f"{guard}{dest} = subgroupShuffleXor({src}, uint({delta}));"
            elif inst.mode == "down":
                return f"{guard}{dest} = subgroupShuffleDown({src}, uint({delta}));"
            elif inst.mode == "up":
                return f"{guard}{dest} = subgroupShuffleUp({src}, uint({delta}));"
            return f"{guard}{dest} = subgroupShuffle({src}, uint({delta}));"

        elif isinstance(inst, SubgroupBallotInst):
            dest = self._clean_reg_name(inst.dest)
            p = self._clean_reg_name(inst.pred)
            return f"{guard}{dest} = subgroupBallot({p}).x;"

        elif isinstance(inst, CooperativeMatrixLoadInst):
            dest = self._clean_reg_name(inst.dest_frag)
            return f"{guard}coopMatLoad({dest}, data_{self._clean_reg_name(inst.ptr)}, 0, {inst.stride}, gl_CooperativeMatrixLayoutRowMajor);"

        elif isinstance(inst, CooperativeMatrixMulAddInst):
            dest = self._clean_reg_name(inst.dest_frag)
            fa = self._clean_reg_name(inst.frag_a)
            fb = self._clean_reg_name(inst.frag_b)
            fc = self._clean_reg_name(inst.frag_c)
            return f"{guard}{dest} = coopMatMulAdd({fa}, {fb}, {fc});"

        elif isinstance(inst, CooperativeMatrixStoreInst):
            src = self._clean_reg_name(inst.src_frag)
            return f"{guard}coopMatStore({src}, data_{self._clean_reg_name(inst.ptr)}, 0, {inst.stride}, gl_CooperativeMatrixLayoutRowMajor);"

        elif isinstance(inst, ReturnInst):
            return f"{guard}return;"

        return ""

    def _clean_reg_name(self, name: str) -> str:
        """Strip %, brackets, and special symbols to make valid GLSL identifier."""
        return name.replace("%", "r_").replace(".", "_").replace("$", "_").replace("[", "").replace("]", "").strip()

    def _map_type(self, t: Any) -> str:
        """Map IR type to GLSL type name."""
        name = str(t).lower()
        mapping = {
            "f16": "float16_t", "f32": "float", "f64": "double",
            "s8": "int8_t", "s16": "int16_t", "s32": "int", "s64": "int64_t",
            "u8": "uint8_t", "u16": "uint16_t", "u32": "uint", "u64": "uint64_t",
            "b8": "uint8_t", "b16": "uint16_t", "b32": "uint", "b64": "uint64_t",
            "pred": "bool"
        }
        return mapping.get(name, "uint")
